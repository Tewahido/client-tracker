// Bundles Edge Functions that reuse the app's code (src/lib) into one file each, because
// Supabase deploys a function's own folder and Deno can't load the app's extensionless
// imports or its npm packages by bare name. `npm:` imports stay as they are for Deno.
//
//   npm run build:functions    writes supabase/functions/<name>/index.ts (not committed)
import { build } from 'esbuild'
import { pathToFileURL } from 'node:url'

/** Functions built from main.ts; the others (send-invite) are deployed as written. */
export const BUNDLED_FUNCTIONS = ['send-reminders']

const BANNER = '// Generated by scripts/build-functions.mjs from main.ts. Do not edit; run npm run build:functions.\n// @ts-nocheck'

export async function buildFunction(name, outfile = `supabase/functions/${name}/index.ts`) {
  await build({
    entryPoints: [`supabase/functions/${name}/main.ts`],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    // Deno fetches these itself, pinned in main.ts.
    external: ['npm:*'],
    banner: { js: BANNER },
    logLevel: 'warning',
  })
  return outfile
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const name of BUNDLED_FUNCTIONS) console.log(`Built ${await buildFunction(name)}`)
}
